const FULLY_TRANSLATED = new Set(["english", "spanish"]);

export const uiLanguage = ref("english");

export function setUiLanguage(lang: string | undefined | null): void {
  uiLanguage.value = SUPPORTED[lang ?? ""] ?? "english";
}

export function isExperimentalUi(lang: string | undefined | null): boolean {
  const mapped = SUPPORTED[lang ?? ""];
  return !!mapped && !FULLY_TRANSLATED.has(mapped);
}

export function t(
  key: MessageKey,
  params?: Record<string, string | number>,
): string {
  let str: string =
    messages[uiLanguage.value]?.[key] ?? en[key];
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.replaceAll(`{${k}}`, String(v));
    }
  }
  return str;
}
